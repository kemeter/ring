//! What Ring asks of the guest besides its root: environment variables and
//! volume mounts, delivered on a small read-only disk (`ring.config=`).
//!
//! The disk holds JSON, padded with zero bytes to a whole number of sectors:
//!
//! ```json
//! {"env": [["KEY", "value"]],
//!  "mounts": [{"device": "/dev/vdc", "destination": "/data", "read_only": false}]}
//! ```
//!
//! It is a disk rather than the kernel command line because the environment
//! often carries secrets, and `/proc/cmdline` is readable by every user of the
//! guest.
//!
//! The environment is written where an image booted with cloud-init would find
//! it from Ring: `/etc/ring/env`, read by every systemd service through a
//! drop-in, and `/etc/profile.d/ring-env.sh` for shells.

use std::path::Path;

use nix::mount::{MsFlags, mount};
use serde::Deserialize;

#[derive(Debug, Default, Deserialize, PartialEq)]
pub(crate) struct GuestConfig {
    #[serde(default)]
    pub(crate) env: Vec<(String, String)>,
    #[serde(default)]
    pub(crate) mounts: Vec<GuestMount>,
}

#[derive(Debug, Deserialize, PartialEq)]
pub(crate) struct GuestMount {
    pub(crate) device: String,
    pub(crate) destination: String,
    #[serde(default)]
    pub(crate) read_only: bool,
}

/// Parse the content of the config disk: JSON up to the first zero byte.
pub(crate) fn parse(disk: &[u8]) -> Result<GuestConfig, String> {
    let end = disk.iter().position(|&b| b == 0).unwrap_or(disk.len());
    serde_json::from_slice(&disk[..end]).map_err(|e| format!("invalid guest config: {}", e))
}

/// Single-quote a value for `KEY='value'` lines, escaping inner single quotes
/// the shell way: `'\''`.
fn shell_quote(value: &str) -> String {
    format!("'{}'", value.replace('\'', r"'\''"))
}

/// `/etc/ring/env`, read by systemd's `EnvironmentFile=`.
fn env_file(env: &[(String, String)]) -> String {
    env.iter()
        .map(|(k, v)| format!("{}={}\n", k, shell_quote(v)))
        .collect()
}

/// `/etc/profile.d/ring-env.sh`, sourced by login shells.
fn profile_script(env: &[(String, String)]) -> String {
    let mut script = String::from("# Auto-generated by Ring — do not edit.\n");
    for (k, v) in env {
        script.push_str(&format!("export {}={}\n", k, shell_quote(v)));
    }
    script
}

/// A drop-in applying `/etc/ring/env` to every systemd service.
const SERVICE_DROPIN: &str = "[Service]\nEnvironmentFile=-/etc/ring/env\n";

/// Write the environment files under `root`, the guest's future root.
pub(crate) fn write_env(root: &Path, env: &[(String, String)]) -> Result<(), String> {
    use std::os::unix::fs::PermissionsExt;

    let files: [(&str, String, u32); 3] = [
        ("etc/ring/env", env_file(env), 0o600),
        ("etc/profile.d/ring-env.sh", profile_script(env), 0o644),
        (
            "etc/systemd/system/service.d/ring-env.conf",
            SERVICE_DROPIN.to_string(),
            0o644,
        ),
    ];
    for (relative, content, mode) in files {
        let path = root.join(relative);
        if let Some(dir) = path.parent() {
            std::fs::create_dir_all(dir)
                .map_err(|e| format!("cannot create {}: {}", dir.display(), e))?;
        }
        std::fs::write(&path, content)
            .and_then(|()| std::fs::set_permissions(&path, std::fs::Permissions::from_mode(mode)))
            .map_err(|e| format!("cannot write {}: {}", path.display(), e))?;
    }
    Ok(())
}

/// Mount each volume at its destination under `root`. The mounts move with
/// the root when it becomes `/`.
pub(crate) fn mount_volumes(
    root: &Path,
    mounts: &[GuestMount],
    wait_for: impl Fn(&str) -> Result<(), String>,
) -> Result<(), String> {
    for m in mounts {
        let relative = m.destination.trim_start_matches('/');
        if relative.is_empty() || relative.split('/').any(|part| part == "..") {
            return Err(format!("refusing to mount on {:?}", m.destination));
        }
        let target = root.join(relative);
        std::fs::create_dir_all(&target)
            .map_err(|e| format!("cannot create {}: {}", target.display(), e))?;
        wait_for(&m.device)?;
        let flags = if m.read_only {
            MsFlags::MS_RDONLY
        } else {
            MsFlags::empty()
        };
        mount(
            Some(m.device.as_str()),
            &target,
            Some("ext4"),
            flags,
            None::<&str>,
        )
        .map_err(|e| format!("cannot mount {} on {}: {}", m.device, m.destination, e))?;
        eprintln!(
            "[ring-init] mounted {} on {}{}",
            m.device,
            m.destination,
            if m.read_only { " (read-only)" } else { "" }
        );
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_config_disk_is_json_up_to_the_padding() {
        let mut disk = br#"{"env":[["A","1"]],"mounts":[{"device":"/dev/vdc","destination":"/data","read_only":true}]}"#.to_vec();
        disk.resize(512, 0);

        let config = parse(&disk).unwrap();
        assert_eq!(config.env, vec![("A".to_string(), "1".to_string())]);
        assert_eq!(
            config.mounts,
            vec![GuestMount {
                device: "/dev/vdc".to_string(),
                destination: "/data".to_string(),
                read_only: true,
            }]
        );
    }

    #[test]
    fn an_empty_config_needs_no_field() {
        assert_eq!(parse(b"{}\0\0").unwrap(), GuestConfig::default());
        assert!(parse(b"not json").is_err());
    }

    #[test]
    fn env_files_quote_their_values_like_cloud_init_did() {
        let env = vec![
            ("GREETING".to_string(), "it's a test".to_string()),
            ("EMPTY".to_string(), String::new()),
        ];
        assert_eq!(env_file(&env), "GREETING='it'\\''s a test'\nEMPTY=''\n");
        assert!(profile_script(&env).contains("export GREETING='it'\\''s a test'\n"));
    }

    #[test]
    fn env_files_land_under_the_new_root_with_their_modes() {
        use std::os::unix::fs::PermissionsExt;

        let root = std::env::temp_dir().join(format!("ring-init-env-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&root);
        write_env(&root, &[("K".to_string(), "v".to_string())]).unwrap();

        let env = root.join("etc/ring/env");
        assert_eq!(std::fs::read_to_string(&env).unwrap(), "K='v'\n");
        assert_eq!(
            std::fs::metadata(&env).unwrap().permissions().mode() & 0o777,
            0o600
        );
        assert_eq!(
            std::fs::read_to_string(root.join("etc/systemd/system/service.d/ring-env.conf"))
                .unwrap(),
            SERVICE_DROPIN
        );

        let _ = std::fs::remove_dir_all(&root);
    }

    #[test]
    fn a_mount_cannot_escape_the_new_root() {
        let root = Path::new("/nonexistent-root");
        for destination in ["/", "", "/../etc", "/data/../../x"] {
            let mounts = vec![GuestMount {
                device: "/dev/vdc".to_string(),
                destination: destination.to_string(),
                read_only: false,
            }];
            let err = mount_volumes(root, &mounts, |_| Ok(())).unwrap_err();
            assert!(err.contains("refusing"), "{destination}: {err}");
        }
    }
}
